/**
 * Index for the left mouse button.
 */
export const MOUSE_LEFT = 0;

/**
 * Index for the middle mouse button (typically the scroll wheel click).
 */
export const MOUSE_MIDDLE = 1;

/**
 * Index for the right mouse button.
 */
export const MOUSE_RIGHT = 2;

/**
 * Type representing valid mouse button indices.
 */
export type MouseButton = 0 | 1 | 2;

